<details class="wp-block-details ks-faq__item"><summary>¿Realizan borrado de tatuajes?</summary><!-- wp:paragraph -->
<p>Sí, contamos con tecnología láser adecuada para remover o aclarar tatuajes, dependiendo del tipo de tinta, color y profundidad.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details {"className":"ks-faq__item"} -->
<details class="wp-block-details ks-faq__item"><summary>¿Cuántas sesiones necesito para borrar un tatuaje?</summary><!-- wp:paragraph -->
<p>Depende del tatuaje. En promedio se requieren entre 6 y 12 sesiones, con intervalos de 6 a 8 semanas para permitir la recuperación de la piel.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details {"className":"ks-faq__item"} -->
<details class="wp-block-details ks-faq__item"><summary>¿Duele el borrado de tatuaje?</summary><!-- wp:paragraph -->
<p>Es un procedimiento tolerable, pero más intenso que la depilación láser. Se utiliza frío y técnicas de confort para reducir molestias.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details {"className":"ks-faq__item"} -->
<details class="wp-block-details ks-faq__item"><summary>¿Puedo depilarme sobre un tatuaje?</summary><!-- wp:paragraph -->
<p>No. El láser de depilación no se pasa directamente sobre el diseño porque podría alterar la tinta o quemar la piel. En esas zonas solo se trabajan los bordes externos.</p>
