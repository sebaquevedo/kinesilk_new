<!-- /wp:heading -->
<!-- wp:details {"className":"ks-faq__item"} -->
<details class="wp-block-details ks-faq__item"><summary>¿Qué es el Hollywood Peel?</summary><!-- wp:paragraph -->
<p>Un peeling láser donde se aplica carbón activado sobre la piel; al aplicar el láser genera luminosidad, afina poros y mejora la textura sin dolor ni tiempo de recuperación.</p>
<!-- /wp:paragraph --></details>
