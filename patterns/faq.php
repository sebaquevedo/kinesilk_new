<div class="wp-block-group ks-faq__group"><!-- wp:heading {"level":3,"className":"ks-faq__group-title"} -->
<h3 class="wp-block-heading ks-faq__group-title">Despigmentación láser</h3>
<!-- /wp:heading -->
<!-- wp:details {"className":"ks-faq__item"} -->
<details class="wp-block-details ks-faq__item"><summary>¿Qué es la despigmentación láser?</summary><!-- wp:paragraph -->
<p>Es un tratamiento que utiliza energía láser para aclarar manchas, equilibrar la melanina y mejorar el tono de la piel. Es ideal para melasma, lentigos solares, manchas por edad, daño solar y pigmentación profunda.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details {"className":"ks-faq__item"} -->
<details class="wp-block-details ks-faq__item"><summary>¿La despigmentación láser duele?</summary><!-- wp:paragraph -->
<p>Es bien tolerada. Se siente como un leve calor o pequeños chispazos sobre la piel. Usamos técnicas de enfriamiento para mayor confort.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details {"className":"ks-faq__item"} -->
<details class="wp-block-details ks-faq__item"><summary>¿Cuántas sesiones necesito para despigmentar?</summary><!-- wp:paragraph -->
<p>Depende del tipo de mancha, profundidad y piel. Generalmente entre 4 y 8 sesiones, con intervalos de 15 a 30 días.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details {"className":"ks-faq__item"} -->
<details class="wp-block-details ks-faq__item"><summary>¿El melasma se puede tratar con láser?</summary><!-- wp:paragraph -->
<p>Sí. El láser ayuda a regular la melanina y reducir la pigmentación, pero requiere cuidados especiales. El melasma es crónico, por lo que se recomienda mantención y protector solar diario.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details {"className":"ks-faq__item"} -->
<details class="wp-block-details ks-faq__item"><summary>¿En cuánto tiempo se ven resultados?</summary><!-- wp:paragraph -->
<p>Muchos pacientes ven cambios desde la primera o segunda sesión, pero los resultados más notorios se aprecian después de varias sesiones consecutivas.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details {"className":"ks-faq__item"} -->
<details class="wp-block-details ks-faq__item"><summary>¿Qué cuidados debo tener después de la despigmentación láser?</summary><!-- wp:list -->
<ul class="wp-block-list"><!-- wp:list-item -->
<li>Usar protector solar FPS 50 todos los días</li>
<!-- /wp:list-item -->
<!-- wp:list-item -->
<li>Evitar sol directo por 48–72 horas</li>
<!-- /wp:list-item -->
<!-- wp:list-item -->
<li>Suspender exfoliantes y ácidos 3–5 días</li>
<!-- /wp:list-item -->
<!-- wp:list-item -->
<li>Hidratar la piel</li>
<!-- /wp:list-item -->
<!-- wp:list-item -->
<li>Evitar calor excesivo el primer día</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list --></details>
<!-- /wp:details -->
<!-- wp:details {"className":"ks-faq__item"} -->
<details class="wp-block-details ks-faq__item"><summary>¿Puedo maquillarme después?</summary><!-- wp:paragraph -->
<p>Sí, a las 24 horas si no hay irritación.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details {"className":"ks-faq__item"} -->
<details class="wp-block-details ks-faq__item"><summary>¿Es posible que la mancha oscurezca antes de aclararse?</summary><!-- wp:paragraph -->
<p>Sí, es totalmente normal. Algunas manchas se oscurecen ligeramente los primeros días y luego comienzan a aclarar.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details {"className":"ks-faq__item"} -->
<details class="wp-block-details ks-faq__item"><summary>¿La despigmentación es definitiva?</summary><!-- wp:paragraph -->
<p>El láser elimina y aclara manchas, pero la piel puede volver a pigmentarse con sol, hormonas, calor excesivo o predisposición. El cuidado posterior es clave para mantener resultados.</p>
<!-- /wp:paragraph --></details>
