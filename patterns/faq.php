<h3 class="wp-block-heading ks-faq__group-title">Depilación Láser</h3>
<!-- /wp:heading -->
<!-- wp:details {"className":"ks-faq__item"} -->
<details class="wp-block-details ks-faq__item"><summary>¿La depilación láser duele?</summary><!-- wp:paragraph -->
<p>La mayoría de las personas la describen como una sensación de calor o pequeños “golpecitos”. Es rápida, segura y bien tolerada.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details {"className":"ks-faq__item"} -->
<details class="wp-block-details ks-faq__item"><summary>¿Cuántas sesiones necesito?</summary><!-- wp:paragraph -->
<p>Entre 6 y 10 sesiones según la zona, tipo de piel y tipo de vello.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details {"className":"ks-faq__item"} -->
<details class="wp-block-details ks-faq__item"><summary>¿Puedo depilarme si estoy bronceada?</summary><!-- wp:paragraph -->
<p>Sí, pero recomendamos esperar 7 a 10 días después de una exposición intensa.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details {"className":"ks-faq__item"} -->
<details class="wp-block-details ks-faq__item"><summary>¿Qué cuidados debo tener antes de la sesión?</summary><!-- wp:list -->
<ul class="wp-block-list"><!-- wp:list-item -->
<li>Rasurar unas horas antes para evitar irritación de la piel</li>
<!-- /wp:list-item -->
<!-- wp:list-item -->
<li>No exfoliar 48 horas previas</li>
<!-- /wp:list-item -->
<!-- wp:list-item -->
<li>No usar autobronceante</li>
<!-- /wp:list-item -->
<!-- wp:list-item -->
<li>Asistir con la piel limpia, sin crema, maquillaje ni desodorante</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list --></details>
<!-- /wp:details -->
<!-- wp:details {"className":"ks-faq__item"} -->
<details class="wp-block-details ks-faq__item"><summary>¿Qué cuidados debo tener después de la sesión?</summary><!-- wp:list -->
<ul class="wp-block-list"><!-- wp:list-item -->
<li>Evitar sol directo por 48 horas</li>
<!-- /wp:list-item -->
<!-- wp:list-item -->
<li>Usar FPS 50</li>
<!-- /wp:list-item -->
<!-- wp:list-item -->
<li>Hidratar la piel</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list --></details>
<!-- /wp:details -->
